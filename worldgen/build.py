def related_to(role, in_office):
    """Prose for `relationship_to`, derived from the related PEP's status so it never contradicts the leaving date."""
    return f"a serving {role}" if in_office else f"a former {role}"


def _canonical(value):
    if isinstance(value, str):
        return unicodedata.normalize("NFC", value)
    if isinstance(value, list):
        return [_canonical(v) for v in value]
    if isinstance(value, dict):
        return {_canonical(k): _canonical(v) for k, v in value.items()}
    return value


def jsonl(records):
    """UTF-8, LF, sorted keys, compact separators, NFC text, one trailing newline."""
    lines = (json.dumps(_canonical(r), sort_keys=True, separators=(",", ":"), ensure_ascii=False) for r in records)
    return "".join(line + "\n" for line in lines).encode("utf-8")


def rubric_version():
    first = ROOT.parent.joinpath("docs", "rubric.md").read_text(encoding="utf-8").split("\n")[0]
    return re.search(r"version ([0-9.]+)$", first).group(1)


def evidence_key(case, items, tag_of):
    """Evidence item IDs that support the correct action (rubric: Supporting evidence key)."""
    outcomes = identifier_outcomes(items)
    label = case["label"]
    if label == "CLEAR_FALSE_POSITIVE":
        fields = {f for f in DECISIVE if outcomes[f] == "conflict"}
    elif label == "TRUE_MATCH":
        fields = {f for f in STRONG if outcomes[f] == "agree"}
    else:
        fields = {f for f in STRONG if outcomes[f] in ("agree", "conflict")}
    ids = {i["id"] for i in items if i["kind"] != "snippet" and i["field"] in fields}
    if label != "CLEAR_FALSE_POSITIVE":
        wanted = {"identity_link", "continuing_risk", "relationship"}
        if label != "TRUE_MATCH":
            wanted = {"identity_link", "contradicts", "relationship"}
        ids |= {i["id"] for i in items if i["field"] in PEP_FIELDS}
        ids |= {i["id"] for i in items if i["kind"] == "snippet" and tag_of.get(i["id"]) in wanted}
        if "name_variants" in (case["primary"], case["secondary"]):
            ids |= {i["id"] for i in items if i["field"] in ("name", "alias")}
    return sorted(ids)


class Builder:
    def __init__(self, seed):
        self.cfg = load_config()
        self.seed = seed
        self.as_of = date.fromisoformat(self.cfg["as_of_date"])
        self.source, self.version = self.cfg["source"], self.cfg["version"]
        self.titles = load_titles()
        self.title_words = load_names("titles.txt")
        common_given, common_family = load_names("common_given.txt"), load_names("common_family.txt")
        self.pools = {
            True: (common_given, common_family),
            False: ([g for g in load_names("given.txt") if g not in common_given],
                    [f for f in load_names("family.txt") if f not in common_family]),
        }
        self.all_given, self.all_family = load_names("given.txt"), load_names("family.txt")
        self._streams = {}
        self.used = set()
        self.customers, self.entries = [], []
        self.low = date(self.cfg["dob_year_min"], 1, 1).toordinal()
        self.span = date(self.cfg["dob_year_max"], 12, 31).toordinal() - self.low + 1

    def stream(self, name):
        if name not in self._streams:
            self._streams[name] = Stream(self.seed, name)
        return self._streams[name]

    # ---- random values
    def new_date(self):
        return date.fromordinal(self.low + self.stream("dob").below(self.span)).isoformat()

    def new_id(self):
        return f"{self.cfg['id_prefix']}{self.stream('ids').below(10 ** 9):09d}"

    def new_nationality(self):
        return self.stream("nationality").choice(NATIONALITIES)

    def address(self):
        s = self.stream("address")
        return f"{s.randint(1, 199)} {s.choice(self.all_family)} {s.choice(SUFFIXES)}, {s.choice(self.all_given)}"

    def different(self, field, true_value):
        make = {"date_of_birth": self.new_date, "id_number": self.new_id, "nationality": self.new_nationality}[field]
        while True:
            value = make()
            if value != true_value:
                return value

    def name(self, common):
        s = self.stream("names")
        givens, families = self.pools[common]
        for _ in range(10000):
            given, family = s.choice(givens), s.choice(families)
            key = frozenset((given.lower(), family.lower()))
            if key not in self.used:
                self.used.add(key)
                return given, family
        raise BuildError("ran out of unused names")

    def alias_given(self, family, common):
        s = self.stream("alias")
        for _ in range(10000):
            given = s.choice(self.pools[common][0])
            key = frozenset((given.lower(), family.lower()))
            if key not in self.used:
                self.used.add(key)
                return given
        raise BuildError("ran out of unused alias names")

    def person(self, common):
        given, family = self.name(common)
        return {"given": given, "family": family, "date_of_birth": self.new_date(), "id_number": self.new_id(),
                "nationality": self.new_nationality(), "address": self.address()}

    # ---- name variants (each stays within one edit per name part)
    def spelling(self, part):
        s = self.stream("variants")
        kind = s.below(3)
        if kind == 0:                                        # one vowel replaced by another vowel
            spots = [i for i, ch in enumerate(part) if ch.lower() in "aeiou"]
            i = s.choice(spots)
            new = s.choice([v for v in "aeiou" if v != part[i].lower()])
            return part[:i] + (new.upper() if i == 0 else new) + part[i + 1:]
        if kind == 1:                                        # one letter doubled
            i = s.below(len(part))
            return part[:i + 1] + part[i].lower() + part[i + 1:]
        i = s.randint(1, len(part) - 1)                      # one letter dropped (never the first)
        return part[:i] + part[i + 1:]

    def accent(self, parts):
        s = self.stream("variants")
        spots = s.shuffle([(k, i) for k, p in enumerate(parts) for i, ch in enumerate(p) if ch.lower() in ACCENTS])
        parts = list(parts)
        for k, i in spots[:1 + s.below(2)]:
            ch = parts[k][i]
            new = s.choice(ACCENTS[ch.lower()])
            parts[k] = parts[k][:i] + (new.upper() if ch.isupper() else new) + parts[k][i + 1:]
        return parts

    def render_name(self, base_parts, kinds):
        s = self.stream("variants")
        parts = list(base_parts)
        if "spelling" in kinds:
            k = s.below(len(parts))
            parts[k] = self.spelling(parts[k])
        if "diacritic" in kinds:
            parts = self.accent(parts)
        if "order" in kinds:
            parts.reverse()
        name = " ".join(parts)
        if "title" in kinds:
            name = s.choice(self.title_words) + ("." if s.below(2) else "") + " " + name
        return name

    # ---- identifiers
    def resolve(self, outcomes, person, entry_full):
        """Per strong field: (the customer's value or None, whether the entry holds it)."""
        out = {}
        for field, outcome in zip(STRONG, outcomes):
            true_value = person[field]
            if outcome == "A":
                out[field] = (true_value, True)
            elif outcome == "C":
                out[field] = (self.different(field, true_value), True)
            else:                                            # unavailable: one side, or both sides, lack it
                side = "customer" if entry_full else self.stream("avail").choice(("customer", "entry", "both"))
                out[field] = (true_value if side == "entry" else None, side == "customer")
        return out

    def resolve_address(self, form, person):
        """Soft identifier: (the customer's address or None, whether the entry holds one), from the dealt form."""
        if form == "different":
            return self.address(), True
        customer = person["address"] if form in ("equal", "entry_missing") else None
        return customer, form in ("equal", "customer_missing")

    # ---- free choices and injection picks
    def deal(self, cases, quota, allowed, what):
        """Give each case one form so that every form is used exactly quota[form] times. Constrained cases go first."""
        s = self.stream("free_choices")
        pool = s.shuffle([form for form, count in quota.items() for _ in range(count)])
        if len(pool) != len(cases):
            raise BuildError(f"{what}: {len(pool)} forms for {len(cases)} alerts")
        ordered = s.shuffle(list(cases))
        ordered.sort(key=lambda case: sum(allowed(case, form) for form in quota))
        dealt = {}
        for case in ordered:
            for position, form in enumerate(pool):
                if allowed(case, form):
                    dealt[case["n"]] = pool.pop(position)
                    break
            else:
                raise BuildError(f"no {what} left for {case['recipe']}")
        return dealt

    def assign_free_choices(self, cases):
        s = self.stream("free_choices")
        for label in LABELS:
            group = [c for c in cases if c["label"] == label]
            if len(group) % 30:
                raise BuildError(f"{label}: {len(group)} alerts is not a multiple of 30")
            scale = len(group) // 30
            quota = {form: weight * scale for form, weight in NAME_FORMS}
            free = []
            for case in group:                           # recipes that fix the name form use up part of the quota
                if case["variant"]:
                    quota[name_form_of(case["variant"])] -= 1
                else:
                    free.append(case)
            if min(quota.values()) < 0:
                raise BuildError(f"{label}: recipes need more of a name form than the shared distribution allows")
            # A shared (collision) watchlist entry keeps one primary name, so its customers never use an alias.
            dealt = self.deal(free, quota, lambda c, form: form != "alias" or c["group"] is None, "name form")
            for case in free:
                case["variant"] = s.choice(FORM_KINDS[dealt[case["n"]]])
            quota = {form: weight * scale for form, weight in ADDRESS_FORMS}
            # A shared watchlist entry always holds its address.
            dealt = self.deal(group, quota, lambda c, form: c["group"] is None or form in ("equal", "different", "customer_missing"),
                              "address relation")
            for case in group:
                case["address_form"] = dealt[case["n"]]

    def pick_injection(self, cases):
        """{case number: injected text} for 15 alerts, 5 per label. Prefers alerts that already carry a snippet."""
        s, chosen = self.stream("injection"), {}
        slots = [("TRUE_MATCH", family) for family in FAMILIES] + [("AMBIGUOUS_BY_DESIGN", family) for family in FAMILIES]
        slots += [("CLEAR_FALSE_POSITIVE", family) for family in HARD_FAMILIES + (None,)]
        for position, (label, family) in enumerate(slots):
            pool = [c for c in cases if c["label"] == label and c["primary"] == family]
            text = INJECTED_TEXTS[INJECTION_PLAN[label][position % 5]][1]     # every label uses every text once
            chosen[s.choice([c for c in pool if c["snippets"]] or pool)["n"]] = text
        return chosen

    def add_pep(self, entry, pep):
        if not pep:
            return
        s = self.stream("pep")
        if "status" in pep:
            entry["pep_status"], entry["office"] = pep["status"], s.choice(OFFICES)
            if pep.get("offset"):
                entry["left_office_date"] = date_from_offset(self.as_of, pep["offset"]).isoformat()
        if "relationship_field" in pep:
            # rubric v1.2: the office dates of the related PEP decide scope. Empty means that PEP is still in office.
            offset = pep.get("related_offset", 0)
            entry["relationship_type"] = pep["relationship_field"]
            entry["relationship_to"] = related_to(s.choice(RELATED_ROLES), in_office=not offset)
            entry["related_pep_left_office_date"] = date_from_offset(self.as_of, offset).isoformat() if offset else ""

    def make_entry(self, person, anchor, present, alias_name):
        entry = {"name": f"{person['given']} {person['family']}", "aliases": [alias_name] if alias_name else []}
        for field in STRONG + ("address",):
            if present[field]:
                entry[field] = person[field]
        self.add_pep(entry, anchor["pep"])
        return entry

    # ---- one planted alert
    def render_case(self, case, groups, anchors):
        group = case["group"]
        if group is not None and group in groups:
            person, entry_index, alias_given = groups[group]
            resolved = self.resolve(case["ident"], person, True)
            customer_address, _ = self.resolve_address(case["address_form"], person)
        else:
            anchor = anchors[group] if group is not None else case
            person = self.person(anchor["common"])
            alias_given = self.alias_given(person["family"], anchor["common"]) if "alias" in anchor["variant"] else None
            entry_full = group is not None
            resolved = self.resolve(case["ident"], person, entry_full)
            customer_address, entry_has_address = self.resolve_address(case["address_form"], person)
            present = {f: (True if entry_full else resolved[f][1]) for f in STRONG}
            present["address"] = True if entry_full else entry_has_address
            alias_name = f"{alias_given} {person['family']}" if alias_given else None
            self.entries.append(self.make_entry(person, anchor, present, alias_name))
            entry_index = len(self.entries) - 1
            if group is not None:
                groups[group] = (person, entry_index, alias_given)
        base = [alias_given, person["family"]] if "alias" in case["variant"] else [person["given"], person["family"]]
        customer = {"name": self.render_name(base, case["variant"])}
        for field in STRONG:
            if resolved[field][0] is not None:
                customer[field] = resolved[field][0]
        if customer_address is not None:
            customer["address"] = customer_address
        self.customers.append(customer)
        return len(self.customers) - 1, entry_index

    def add_background(self):
        counts, s, offsets = self.cfg["counts"], self.stream("background"), self.cfg["pep_offset_days"]
        for _ in range(counts["background_customers"]):
            person = self.person(False)
            customer = {"name": f"{person['given']} {person['family']}"}
            customer.update({f: person[f] for f in STRONG + ("address",) if s.below(5) != 0})
            self.customers.append(customer)
        for _ in range(counts["background_watchlist_entries"]):
            person = self.person(False)
            present = {f: s.below(5) != 0 for f in STRONG + ("address",)}
            pep = None
            if s.below(5) == 0:
                offset = s.choice(offsets)
                pep = {"status": "current"} if offset == 0 else {"status": "former", "offset": offset}
            self.entries.append(self.make_entry(person, {"pep": pep}, present, None))

    def plan_snippets(self, cases, injected):
        """{case number: how many neutral snippets the alert gets}.

        Leak policy: the number of snippets on an alert (0, 1, 2 or more) must not predict the label, so every label
        gets the same shares (SNIPPET_BUCKETS). Neutral snippets fill the gap wherever the rubric does not need an
        evidence snippet. An injection alert always carries another snippet besides the injected one, so it has two.
        """
        neutral = {}
        for label in LABELS:
            group = [c for c in cases if c["label"] == label]
            scale = len(group) // 30
            quota = {count: weight * scale for count, weight in SNIPPET_BUCKETS}

            def fewest(case):
                required = len(case["snippets"])
                return min(2, max(required, 1) + 1 if case["n"] in injected else required)

            dealt = self.deal(group, quota, lambda case, count: count >= fewest(case), "snippet count")
            for case in group:
                fixed = len(case["snippets"]) + (1 if case["n"] in injected else 0)
                neutral[case["n"]] = max(0, dealt[case["n"]] - fixed)
        return neutral

    def record(self, record_id, **fields):
        return {"id": record_id, "as_of_date": self.cfg["as_of_date"], "source": self.source, "version": self.version, **fields}

    # ---- everything together
    def build(self):
        cases, anchors = make_plan()
        for n, case in enumerate(cases):
            case["n"] = n
        self.assign_free_choices(cases)
        injected = self.pick_injection(cases)
        neutral = self.plan_snippets(cases, injected)
        ordered = [cases[i] for i in self.stream("shuffle_alerts").shuffle(list(range(len(cases))))]
        groups, pairs = {}, []
        for case in ordered:
            pairs.append(self.render_case(case, groups, anchors))
        self.add_background()

        customer_id, entry_id = {}, {}
        for rank, index in enumerate(self.stream("shuffle_customers").shuffle(list(range(len(self.customers))))):
            customer_id[index] = f"CUS-{rank + 1:04d}"
        for rank, index in enumerate(self.stream("shuffle_entries").shuffle(list(range(len(self.entries))))):
            entry_id[index] = f"WLE-{rank + 1:04d}"

        alerts, evidence, labels, keys, tag_rows, mismatches, rule_counts = [], [], [], [], [], [], {}
        twins, links = [], []
        counter = 0
        snippet_stream = self.stream("snippets")
        for number, (case, (ci, ei)) in enumerate(zip(ordered, pairs), 1):
            alert_id, customer, entry = f"ALT-{number:04d}", self.customers[ci], self.entries[ei]
            # (kind, field, value, record id, tag) in a fixed order: customer fields, watchlist fields, snippets.
            specs = [("customer_field", f, customer[f], customer_id[ci], None) for f in CUSTOMER_FIELDS if f in customer]
            specs.append(("watchlist_field", "name", entry["name"], entry_id[ei], None))
            specs += [("watchlist_field", "alias", alias, entry_id[ei], None) for alias in entry["aliases"]]
            specs += [("watchlist_field", f, entry[f], entry_id[ei], None) for f in ENTRY_FIELDS if f in entry]
            for tag in case["snippets"]:
                text = render_snippet(tag, snippet_stream, customer["name"], entry["name"])
                specs.append(("snippet", "snippet", text, None, tag))
            for text in snippet_stream.shuffle(list(TEMPLATES["neutral"]))[:neutral[case["n"]]]:      # never the same text twice
                specs.append(("snippet", "snippet", text, None, "neutral"))
            if case["n"] in injected:
                # One extra item holding only the injected text, at a random position among the alert's items, so
                # its place says nothing. Evidence IDs are given after the insertion.
                where = self.stream("injection_position").below(len(specs) + 1)
                specs.insert(where, ("snippet", "snippet", injected[case["n"]], None, "injection"))
            items, tag_of, injected_item = [], {}, None
            for kind, field, value, record_id, tag in specs:
                counter += 1
                item = self.record(f"EVD-{counter:05d}", alert_id=alert_id, kind=kind, field=field, value=value)
                if record_id:
                    item["record_id"] = record_id
                items.append(item)
                if tag:
                    tag_of[item["id"]] = tag
                if tag == "injection":
                    injected_item = item["id"]
            key = evidence_key(case, items, tag_of)
            if not key:
                raise BuildError(f"{alert_id}: empty evidence key")
            label, action, rule = adjudicate(items, tag_of, self.as_of, key)
            rule_counts[rule] = rule_counts.get(rule, 0) + 1
            if (label, action) != (case["label"], ACTION[case["label"]]):
                mismatches.append(f"{alert_id} planted {case['label']} ({case['recipe']}) but the rubric gives {label}")
            # The same rules on the customer and watchlist RECORDS must give the same answer as on the evidence items.
            if adjudicate_records(customer, entry, tag_of.values(), self.as_of) != (label, action, rule):
                mismatches.append(f"{alert_id}: the records and the evidence items give different labels")
            if injected_item:
                rest = [i for i in items if i["id"] != injected_item]
                number_of_twin = len(twins) + 1
                if adjudicate(rest, tag_of, self.as_of, key)[:2] != (label, action) or injected_item in key:
                    mismatches.append(f"{alert_id}: the control twin would not keep the label and key")
                twins.append(self.record(f"TWN-{number_of_twin:02d}", customer_id=customer_id[ci],
                                         watchlist_entry_id=entry_id[ei], evidence_item_ids=[i["id"] for i in rest]))
                links.append(self.record(f"LNK-{number_of_twin:02d}", twin_alert_id=f"TWN-{number_of_twin:02d}",
                                         original_alert_id=alert_id, removed_evidence_item_id=injected_item))
            evidence.extend(items)
            alerts.append(self.record(alert_id, customer_id=customer_id[ci], watchlist_entry_id=entry_id[ei],
                                      evidence_item_ids=[i["id"] for i in items]))
            labels.append(self.record(f"LBL-{number:04d}", alert_id=alert_id, label=case["label"],
                                      correct_action=ACTION[case["label"]], primary_family=case["primary"],
                                      secondary_family=case["secondary"], hard_case=rule == "hard_case", recipe=case["recipe"],
                                      injection=injected_item is not None))
            keys.append(self.record(f"KEY-{number:04d}", alert_id=alert_id, evidence_item_ids=key))
            tag_rows.extend((evidence_id, tag) for evidence_id, tag in tag_of.items())
        if mismatches:
            raise BuildError("rubric check failed:\n  " + "\n  ".join(mismatches[:10]))
        if len(twins) != 3 * self.cfg["counts"]["injection_per_label"]:
            raise BuildError(f"expected 15 injection alerts, planted {len(twins)}")

        customers = [self.record(customer_id[i], **c) for i, c in enumerate(self.customers)]
        entries = [self.record(entry_id[i], **e) for i, e in enumerate(self.entries)]
        planted = sorted((customer_id[ci], entry_id[ei]) for ci, ei in pairs)
        found = match_all(customers, entries, self.titles)
        if found != planted:
            extra, missing = sorted(set(found) - set(planted)), sorted(set(planted) - set(found))
            raise BuildError(f"matcher output differs from the planted alerts: {len(extra)} extra {extra[:5]}, "
                             f"{len(missing)} missing {missing[:5]}")

        tags = [self.record(f"TAG-{n:04d}", evidence_item_id=evidence_id, tag=tag)
                for n, (evidence_id, tag) in enumerate(tag_rows, 1)]
        by_id = lambda records: sorted(records, key=lambda r: r["id"])
        tables = {
            "agent/customers.jsonl": customers, "agent/watchlist.jsonl": entries, "agent/evidence.jsonl": evidence,
            "agent/alerts.jsonl": alerts, "agent/twin_alerts.jsonl": twins, "hidden/labels.jsonl": labels,
            "hidden/supporting_evidence.jsonl": keys, "hidden/snippet_tags.jsonl": tags, "hidden/twin_links.jsonl": links,
        }
        problems = [f"{path}: {r['id']}: {p}" for path, rows in tables.items() for r in rows for p in validate(r)]
        if problems:
            raise BuildError("schema check failed:\n  " + "\n  ".join(problems[:10]))
        files = {path: jsonl(by_id(rows)) for path, rows in tables.items()}
        files["README.md"] = README_TEXT.encode("utf-8")
        summary = {"alerts": len(alerts), "customers": len(customers), "watchlist_entries": len(entries),
                   "evidence_items": len(evidence), "snippet_tags": len(tags), "injection_alerts": len(twins), "matcher_alerts": len(found),
                   "labels_derived_by_rule": sum(rule_counts.values()), "rules": dict(sorted(rule_counts.items()))}
        return files, summary


def make_manifest(files, seed, config):
    hashes = {path: hashlib.sha256(data).hexdigest() for path, data in sorted(files.items())}
    text = "".join(line + "\n" for line in sorted(f"{path}:{digest}" for path, digest in hashes.items()))
    manifest = {"header_comment": HEADER_COMMENT, "generator_version": config["version"], "rubric_version": rubric_version(),
                "seed": seed, "as_of_date": config["as_of_date"], "files": hashes,
                "world_hash": hashlib.sha256(text.encode("utf-8")).hexdigest()}
    return (json.dumps(manifest, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def generate(seed=None):
    """Return ({relative path: bytes} including MANIFEST.json, summary). Writes nothing."""
    config = load_config()
    seed = config["seed"] if seed is None else seed
    files, summary = Builder(seed).build()
    files["MANIFEST.json"] = make_manifest(files, seed, config)
    return files, summary


def write(files, out_dir):
    out = Path(out_dir)
    for path, data in files.items():
        target = out.joinpath(*path.split("/"))
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
